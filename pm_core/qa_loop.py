def _resolve_interactive_model(pr_data: dict, data: dict):
    """Model for Scenario 0: ``qa_interactive`` (falls back to ``qa``).

    Scenario 0 is the session the user drives / remote-controls, so it
    never follows ``qa_scenario`` onto a worker route.  Configs from
    before ``qa_interactive`` that set only ``qa_scenario`` to a plain
    model keep that model for s0.
    """
    res = _resolve_qa_model(pr_data, data, session_type="qa_interactive")
    if not res.model and not res.provider:
        legacy = _resolve_qa_model(pr_data, data, session_type="qa_scenario")
        if legacy.model and not legacy.provider:
            res.model = legacy.model
            res.effort = res.effort or legacy.effort
    return res


def _launch_scenario_0(
    state: QALoopState,
    data: dict,
    pr_data: dict,
    session: str,
    repo_root: Path | None,
    workdir_path: str,
) -> QAScenario | None:
    """Launch Scenario 0: a persistent interactive Claude session.

    Returns the QAScenario object (not added to state.scenarios — it is
    tracked separately so it is never polled for verdicts).
    """
    from pm_core import tmux as tmux_mod, prompt_gen
    from pm_core.claude_launcher import build_claude_shell_cmd
    _qa_resolution = _resolve_interactive_model(pr_data, data)

    scenario = QAScenario(
        index=0,
        title="Interactive Session",
        focus="Manual testing and exploration",
    )

    branch = pr_data.get("branch", "")
    try:
        clone_path, scratch_path = create_scenario_workdir(
            Path(state.qa_workdir), 0,
            repo_root=repo_root,
            pr_id=state.pr_id,
            loop_id=state.loop_id,
            branch=branch,
        )
    except Exception:
        _log.warning("Failed to create workdir for Scenario 0, skipping")
        return None

    scenario.worktree_path = str(clone_path)

    if repo_root:
        _setup_clone_override(clone_path)

    # Scenario 0 always runs on the host (not in a container) so the user
    # has full access to host tools, git credentials, and the TUI session.
    child_prompt = prompt_gen.generate_qa_interactive_prompt(
        data, state.pr_id,
        workdir=str(clone_path),
        session_name=session,
        worktree_mode=bool(repo_root),
        scratch_dir=str(scratch_path),
    )

    scenario_cwd = str(clone_path) if repo_root else workdir_path
    final_cmd = build_claude_shell_cmd(
        prompt=child_prompt,
        model=_qa_resolution.model, provider=_qa_resolution.provider, effort=_qa_resolution.effort,
        cwd=scenario_cwd,
        # Fake-claude keeps treating s0 as a scenario session; only model
        # targeting moved to qa_interactive.
        session_type="qa_scenario",
        session_tag=state.session_tag)

    win_name = _scenario_window_name(pr_data, 0)
    try:
        pane_id = tmux_mod.new_window_get_pane(session, win_name, final_cmd,
                                               cwd=scenario_cwd, switch=False)
        scenario.window_name = win_name
        scenario.pane_id = pane_id
    except Exception:
        _log.warning("Failed to create window for Scenario 0")
        return None

    _log.info("Launched Scenario 0 (interactive) in window %s", win_name)
    try:
        from pm_core import pane_layout
        win_id = tmux_mod.pane_window_id(pane_id)
        if win_id:
            pane_layout.register_and_rebalance(
                session, win_id, [(pane_id, "qa-scenario-s0", final_cmd)])
    except Exception:
        _log.debug("Registration/rebalance failed for Scenario 0", exc_info=True)
    return scenario


