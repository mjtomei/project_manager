def generate_new_mocks(requests: list[NewMockRequest], workdir: str,
                       pm_root: Path) -> int:
    """Generate mock definitions for all requests, skipping existing ones.

    Runs generations sequentially.  Returns the count of successfully
    generated (or already-existing) mocks.
    """
    if not requests:
        return 0

    _log.info("Generating %d new mock definition(s)", len(requests))
    success = 0
    for req in requests:
        if _generate_new_mock(req, workdir, pm_root):
            success += 1
    return success


