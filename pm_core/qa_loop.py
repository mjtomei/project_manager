def _install_instruction_file(pm_root: Path, scenario: QAScenario,
                              scratch_path: Path,
                              scratch_dir: str) -> None:
    """Copy the instruction file into the scenario's scratch area.

    The instruction library lives in the pm project, not in the target repo.
    This copies the referenced file into ``{scratch_path}/qa-instructions/``
    and rewrites ``scenario.instruction_path`` to the absolute path as seen
    by the agent (``{scratch_dir}/qa-instructions/{filename}``).

    *scratch_path* is the host-side path; *scratch_dir* is the path the
    agent sees (same on host, ``/scratch`` in containers).
    """
    if not scenario.instruction_path:
        return
    # instruction_path is e.g. "instructions/tui-manual-test.md"
    src = pm_root / "qa" / scenario.instruction_path
    if not src.is_file():
        _log.warning("Instruction file %s not found — clearing instruction_path",
                      src)
        scenario.instruction_path = None
        return
    dest_dir = scratch_path / "qa-instructions"
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / src.name
    import shutil
    shutil.copy2(src, dest)
    scenario.instruction_path = f"{scratch_dir}/qa-instructions/{src.name}"
    _log.info("Copied instruction %s -> %s", src, dest)


def _write_scenario_capture_file(pr_id: str, scenario_index: int,
                                  name: str, content: str,
                                  session_tag: str | None = None,
                                  ) -> Path | None:
    """Write a per-scenario capture file under the host captures dir.

    Path: ``~/.pm/sessions/<session-tag>/captures/<pr_id>/scenarios/<n>/<name>``.

    Captures live under the active pm session's sessions dir so they
    don't bloat git history — they're ephemeral artifacts of pm's
    process, like workdirs. Scenario containers bind-mount this
    directory to ``/pm-captures/``. Returns the written path or
    ``None`` on failure.

    *session_tag* should be the orchestrator's tmux-derived tag (from
    ``QALoopState.session_tag``) so this lands in the same dir the
    review pane's bind-mount and scenario containers' ``/pm-captures``
    point at. Callers that don't supply one fall back to
    :func:`captures_dir`'s tmux-then-cwd resolution.
    """
    try:
        from pm_core.paths import captures_dir
        base = captures_dir(pr_id, session_tag=session_tag)
        if base is None:
            _log.warning("captures_dir unavailable for pr=%s (no session tag)",
                         pr_id)
            return None
        dest_dir = base / "scenarios" / str(scenario_index)
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / name
        dest.write_text(content)
        return dest
    except Exception:
        _log.warning("Failed to write %s for scenario %d (pr=%s)",
                     name, scenario_index, pr_id, exc_info=True)
        return None


def _persist_scenario_verdicts(state: "QALoopState", branch: str) -> None:
    """Write each scenario's final verdict under the host captures dir.

    Resolves to ``~/.pm/sessions/<tag>/captures/<pr_id>/scenarios/<n>/verdict.md``
    via :func:`_write_scenario_capture_file`, which keys off
    ``state.session_tag`` so the path matches what the review pane's
    bind-mount and scenario containers' ``/pm-captures`` point at.
    The ``branch`` arg is kept for signature stability but no longer
    drives any git operation — workers don't commit-and-push captures
    anymore.
    """
    _ = branch  # kept for caller compatibility
    for s in state.scenarios:
        verdict = state.scenario_verdicts.get(s.index, "")
        if not verdict:
            continue
        reason = state.scenario_verdict_reasons.get(s.index, "")
        body = f"# Scenario {s.index}: {s.title}\n\n{verdict}\n"
        if reason:
            body += f"\n{reason}\n"
        _write_scenario_capture_file(
            state.pr_id, s.index, "verdict.md", body,
            session_tag=state.session_tag,
        )
        # Also persist a structured per-scenario record so the sign-off
        # agent (pr-2d5f712 + pr-8e693f6) can synthesize the BDD framing
        # (steps / focus / verdict / reason) into report.html without
        # re-parsing the markdown verdict.md, and the live qa_status.json
        # lives in an ephemeral workdir. JSON is additive; older captures
        # without it fall back to verdict.md.
        record = {
            "index": s.index,
            "title": s.title,
            "focus": s.focus,
            "steps": s.steps,
            "verdict": verdict,
            "reason": reason,
        }
        _write_scenario_capture_file(
            state.pr_id, s.index, "scenario.json",
            json.dumps(record, indent=2),
            session_tag=state.session_tag,
        )


def _install_artifact_files(pm_root: Path, scenario: QAScenario,
                            scratch_path: Path,
                            scratch_dir: str) -> None:
    """Copy referenced artifact recipes into the scenario's scratch dir.

    Parallel to ``_install_instruction_file`` but for artifact recipes
    and supports multiple recipes per scenario. Recipes are *not*
    inlined into the steps — they stay files the worker reads at
    execution time, so the scenario prompt surfaces paths rather than
    bodies.

    Rewrites ``scenario.artifact_paths`` to absolute paths the agent
    sees (``{scratch_dir}/qa-artifacts/{filename}``). Recipes that
    can't be located on disk are dropped from the list with a warning.
    """
    if not scenario.artifact_paths:
        return
    import shutil
    dest_dir = scratch_path / "qa-artifacts"
    dest_dir.mkdir(parents=True, exist_ok=True)
    new_paths: list[str] = []
    for rel in scenario.artifact_paths:
        # rel is e.g. "artifacts/tmux-screen-recording.md"
        src = pm_root / "qa" / rel
        if not src.is_file():
            _log.warning("Artifact recipe %s not found — dropping from scenario",
                          src)
            continue
        dest = dest_dir / src.name
        shutil.copy2(src, dest)
        new_paths.append(f"{scratch_dir}/qa-artifacts/{src.name}")
        _log.info("Copied artifact recipe %s -> %s", src, dest)
    scenario.artifact_paths = new_paths


def _drop_deferred_launch(session: str, scenario: "QAScenario",
                          win_name: str | None, deferred: dict | None,
                          container_name: str | None = None) -> None:
    """Undo a queued launch deferred by its route gate: close the refiner
    window and remove the container created for it.  The scenario goes
    back to the queue and is prepared afresh (refiner included) once the
    route is usable.  The container must go: that preparation re-clones
    the workdir, and a container reused by name would keep its bind mount
    on the deleted clone."""
    if deferred is None or scenario.index not in deferred:
        return
    from pm_core import tmux as tmux_mod
    if win_name:
        try:
            tmux_mod.kill_window(session, win_name)
        except Exception:
            _log.debug("could not close deferred window %s", win_name,
                       exc_info=True)
    if container_name:
        from pm_core import container as container_mod
        try:
            container_mod.remove_container(container_name)
        except Exception:
            _log.warning("could not remove deferred container %s",
                         container_name, exc_info=True)


def _launch_scenarios_in_tmux(
    state: QALoopState,
    data: dict,
    pr_data: dict,
    session: str,
    repo_root: Path | None,
    workdir_path: str,
    pm_root: Path | None = None,
    _status_scenarios: list | None = None,
    _status_queued: set[int] | None = None,
    _route_deferred: dict | None = None,
) -> None:
    """Launch each scenario in its own tmux window (with worktree isolation).

    *_route_deferred* (queued launches): launch gates do not wait on an
    unusable route, see :func:`_route_gate`.

    *_status_scenarios* / *_status_queued*: the run's full scenario list and
    the indices still waiting in the launch queue, so the dashboard status
    written here keeps showing queued scenarios as ``queued``.

    Both phases run in parallel: workdir cloning, concretizer window creation,
    and agent launch all happen concurrently across scenarios.  The scenario
    agent pane is split as soon as its concretizer finishes.
    """
    from pm_core import tmux as tmux_mod
    _qa_resolution = _resolve_qa_model(pr_data, data, session_type="qa_scenario")

    branch = pr_data.get("branch", "")

    # --- Phase 1: clone workdirs and create concretizer windows in parallel ---
    # Each entry: (scenario, concretize_pane, scenario_cwd, clone_path, scratch_path, transcript)
    pending: list[tuple] = []
    pending_lock = threading.Lock()

    def _prepare_scenario(scenario: QAScenario) -> None:
        if state.stop_requested:
            return

        try:
            clone_path, scratch_path = create_scenario_workdir(
                Path(state.qa_workdir), scenario.index,
                repo_root=repo_root,
                pr_id=state.pr_id,
                loop_id=state.loop_id,
                branch=branch,
                expected_head=state.planner_head,
            )
        except Exception as exc:
            _log.warning("Failed to create workdir for scenario %d, "
                         "skipping: %s", scenario.index, exc)
            state.scenario_verdict_reasons[scenario.index] = (
                f"workdir setup failed: {exc}")
            return
        scenario.worktree_path = str(clone_path)

        if repo_root:
            _setup_clone_override(clone_path)

        # Read instruction content before installing (sets absolute path on scenario)
        instruction_content: str | None = None
        if pm_root and scenario.instruction_path:
            src = pm_root / "qa" / scenario.instruction_path
            if src.is_file():
                try:
                    instruction_content = src.read_text()
                except Exception:
                    pass
            _install_instruction_file(pm_root, scenario, scratch_path,
                                      scratch_dir=str(scratch_path))
            # Steps will be inlined by concretizer — worker doesn't need the file ref
            scenario.instruction_path = None

        # Artifact recipes get copied into scratch but their paths stay on
        # the scenario so the worker sees them.
        if pm_root and scenario.artifact_paths:
            _install_artifact_files(pm_root, scenario, scratch_path,
                                    scratch_dir=str(scratch_path))

        scenario_cwd = str(clone_path) if repo_root else workdir_path
        transcript = _scenario_transcript_path(state.qa_workdir, scenario.index)
        win_name = _scenario_window_name(pr_data, scenario.index)

        if not _route_gate(state, pr_data, data, scenario, "qa_concretize",
                           deferred=_route_deferred):
            return

        import uuid as _uuid
        scenario.concretize_session_id = str(_uuid.uuid4())
        concretize_cmd = _build_concretize_cmd(
            scenario, pr_data, data, cwd=scenario_cwd,
            instruction_content=instruction_content,
            session_id=scenario.concretize_session_id,
            session_tag=state.session_tag)
        try:
            concretize_pane = tmux_mod.new_window_get_pane(
                session, win_name, concretize_cmd,
                cwd=scenario_cwd, switch=False)
        except Exception:
            concretize_pane = None
        if not concretize_pane:
            _log.warning("Failed to create window for scenario %d",
                         scenario.index)
            return

        # Set window_name now so the status dashboard can navigate to
        # the concretizer window during the concretization phase.
        scenario.window_name = win_name
        with pending_lock:
            pending.append((scenario, concretize_pane, scenario_cwd,
                            clone_path, scratch_path, transcript, win_name,
                            instruction_content))

    prep_threads = [
        threading.Thread(target=_prepare_scenario, args=(sc,), daemon=True,
                         name=f"prepare-s{sc.index}")
        for sc in state.scenarios
    ]
    for t in prep_threads:
        t.start()
    for t in prep_threads:
        t.join()

    # Write status with window names so the dashboard is navigable
    # while concretizers run (before the polling loop starts).
    if state.qa_workdir and pending:
        _write_status_file(
            Path(state.qa_workdir) / "qa_status.json",
            state.pr_id,
            _status_scenarios if _status_scenarios is not None else state.scenarios,
            state.scenario_verdicts,
            scenario_0=state.scenario_0,
            queued_scenarios=_status_queued,
            verdict_reasons=state.scenario_verdict_reasons,
        )

    # --- Phase 2: poll concretizers in parallel, launch agent as each finishes ---
    def _concretize_and_launch(
            scenario: QAScenario,
            concretize_pane: str,
            scenario_cwd: str,
            clone_path: Path,
            scratch_path: Path,
            transcript: str,
            win_name: str,
            instruction_content: str | None = None,
    ) -> None:
        refined_steps, reject_reason = _concretize_scenario(
            scenario, pr_data, data, concretize_pane,
            session_id=scenario.concretize_session_id,
            scenario_cwd=scenario_cwd,
            instruction_content=instruction_content,
            route_watch=_RouteStallWatch(
                state, _route_checker(pr_data, data, "qa_concretize",
                                      session_tag=state.session_tag),
                f"Scenario {scenario.index} refiner"),
        )
        if reject_reason:
            state.scenario_verdicts[scenario.index] = VERDICT_INPUT_REQUIRED
            state.scenario_verdict_reasons[scenario.index] = (
                _concretize_failure_label(reject_reason)
            )
            state.latest_output = (
                f"Scenario {scenario.index} ({scenario.title}): "
                f"{VERDICT_INPUT_REQUIRED} — {_concretize_failure_label(reject_reason)}"
            )
            _log.info("Refiner rejected scenario %d — skipping worker launch: %s",
                      scenario.index, reject_reason)
            return
        if refined_steps:
            scenario.steps = refined_steps

        if not _route_gate(state, pr_data, data, scenario, "qa_scenario",
                           deferred=_route_deferred):
            _drop_deferred_launch(session, scenario, win_name, _route_deferred)
            return
        child_cmd, pane_cwd = _build_scenario_run_cmd(
            scenario, state, data, transcript, _qa_resolution,
            session=session, workdir_path=workdir_path,
        )

        try:
            scenario_pane = tmux_mod.split_pane_at(
                concretize_pane, "v", child_cmd, background=True,
                cwd=pane_cwd)
            scenario.window_name = win_name
            scenario.pane_id = scenario_pane
            scenario.transcript_path = transcript
            try:
                from pm_core.claude_launcher import session_id_from_transcript
                scenario.session_id = session_id_from_transcript(transcript)
            except Exception:
                scenario.session_id = None
        except Exception:
            _log.warning("Failed to split scenario pane for scenario %d",
                         scenario.index, exc_info=True)

        if scenario.window_name:
            _log.info("Launched scenario %d (%s) in window %s",
                      scenario.index, scenario.title, win_name)
            try:
                from pm_core import pane_layout
                win_id = tmux_mod.pane_window_id(concretize_pane)
                if win_id:
                    pane_layout.register_and_rebalance(session, win_id, [
                        (concretize_pane, f"qa-concretize-s{scenario.index}", "concretize"),
                        (scenario_pane, f"qa-scenario-s{scenario.index}", child_cmd),
                    ])
            except Exception:
                _log.debug("Registration/rebalance failed for scenario %d",
                           scenario.index, exc_info=True)
        else:
            _log.warning("Scenario %d (%s) window creation failed",
                         scenario.index, scenario.title)

    threads = [
        threading.Thread(
            target=_concretize_and_launch,
            args=entry,
            daemon=True,
            name=f"concretize-{entry[0].index}",
        )
        for entry in pending
    ]
    for t in threads:
        t.start()
    for t in threads:
        t.join()


def _launch_scenarios_in_containers(
    state: QALoopState,
    data: dict,
    pr_data: dict,
    session: str,
    repo_root: Path | None,
    workdir_path: str,
    pm_root: Path | None = None,
    _status_scenarios: list | None = None,
    _status_queued: set[int] | None = None,
    _route_deferred: dict | None = None,
) -> None:
    """Launch each scenario in a Docker container, presented via a tmux window.

    *_route_deferred*: as for :func:`_launch_scenarios_in_tmux`.

    Each scenario gets:
      1. A local clone of the repo (standalone .git, no worktree pointers)
      2. A detached container with the clone mounted at /workspace
      3. A push proxy scoped to the PR branch
      4. A tmux window running ``docker exec -it <container> claude ...``

    The user sees the same tmux windows as in non-container mode, but the
    claude process is isolated inside the container.  Polling and verdict
    extraction happen via tmux pane capture, identical to the tmux path.
    """
    from pm_core import tmux as tmux_mod
    from pm_core import container as container_mod
    _qa_resolution = _resolve_qa_model(pr_data, data, session_type="qa_scenario")

    config = container_mod.load_container_config()
    branch = pr_data.get("branch", "")

    # Session tag for container naming, shared push proxies, and the
    # captures bind-mount. ``state.session_tag`` was captured in
    # ``run_qa_sync`` from the same tmux session — reuse it so every
    # caller agrees on the path.
    _session_tag = state.session_tag

    # In container mode, paths inside the container are fixed
    container_workdir = container_mod._CONTAINER_WORKDIR
    container_scratch = container_mod._CONTAINER_SCRATCH

    # --- Phase 1: clone workdirs, create containers and windows in parallel ---
    # Each entry: (scenario, concretize_pane, win_name, cname, transcript, clone_path, instruction_content)
    pending: list[tuple] = []
    pending_lock = threading.Lock()

    def _prepare_scenario(scenario: QAScenario) -> None:
        if state.stop_requested:
            return

        try:
            clone_path, scratch_path = create_scenario_workdir(
                Path(state.qa_workdir), scenario.index,
                repo_root=repo_root,
                pr_id=state.pr_id,
                loop_id=state.loop_id,
                branch=branch,
                expected_head=state.planner_head,
            )
        except Exception as exc:
            _log.warning("Failed to create workdir for scenario %d, "
                         "skipping: %s", scenario.index, exc)
            state.scenario_verdict_reasons[scenario.index] = (
                f"workdir setup failed: {exc}")
            return
        scenario.worktree_path = str(clone_path)

        # Read instruction content from source before installing
        instruction_content: str | None = None
        if pm_root and scenario.instruction_path:
            src = pm_root / "qa" / scenario.instruction_path
            if src.is_file():
                try:
                    instruction_content = src.read_text()
                except Exception:
                    pass
            _install_instruction_file(pm_root, scenario, scratch_path,
                                      scratch_dir=container_scratch)
            # Steps will be inlined by concretizer — worker doesn't need the file ref
            scenario.instruction_path = None

        # Artifact recipes get copied into scratch but their paths stay on
        # the scenario so the worker sees them.
        if pm_root and scenario.artifact_paths:
            _install_artifact_files(pm_root, scenario, scratch_path,
                                    scratch_dir=container_scratch)

        transcript = _scenario_transcript_path(state.qa_workdir, scenario.index)

        cname = container_mod.qa_container_name(
            state.pr_id, state.loop_id, scenario.index,
            session_tag=_session_tag,
        )
        try:
            container_mod.create_qa_container(
                name=cname,
                config=config,
                workdir=clone_path,
                scratch_path=scratch_path,
                allowed_push_branch=branch or None,
                session_tag=_session_tag,
                pr_id=state.pr_id,
                route_mounts=_route_mounts(pr_data, data, _session_tag),
            )
            scenario.container_name = cname
        except Exception:
            _log.error("Failed to create container for scenario %d — aborting scenario",
                       scenario.index, exc_info=True)
            return

        win_name = _scenario_window_name(pr_data, scenario.index)

        if not _route_gate(state, pr_data, data, scenario, "qa_concretize",
                           container_name=cname, deferred=_route_deferred):
            _drop_deferred_launch(session, scenario, None, _route_deferred,
                                  container_name=cname)
            return

        import uuid as _uuid
        scenario.concretize_session_id = str(_uuid.uuid4())
        concretize_cmd = _build_concretize_cmd(
            scenario, pr_data, data, cwd=container_workdir,
            container_name=cname, instruction_content=instruction_content,
            write_dir=str(clone_path),
            session_id=scenario.concretize_session_id,
            session_tag=state.session_tag)
        try:
            concretize_pane = tmux_mod.new_window_get_pane(
                session, win_name, concretize_cmd,
                cwd=workdir_path, switch=False)
        except Exception:
            concretize_pane = None
        if not concretize_pane:
            _log.warning("Failed to create window for scenario %d",
                         scenario.index)
            return

        # Set window_name now so the status dashboard can navigate to
        # the concretizer window during the concretization phase.
        scenario.window_name = win_name
        with pending_lock:
            pending.append((scenario, concretize_pane, win_name, cname, transcript,
                            clone_path, instruction_content))

    prep_threads = [
        threading.Thread(target=_prepare_scenario, args=(sc,), daemon=True,
                         name=f"prepare-s{sc.index}")
        for sc in state.scenarios
    ]
    for t in prep_threads:
        t.start()
    for t in prep_threads:
        t.join()

    # Write status with window names so the dashboard is navigable
    # while concretizers run (before the polling loop starts).
    if state.qa_workdir and pending:
        _write_status_file(
            Path(state.qa_workdir) / "qa_status.json",
            state.pr_id,
            _status_scenarios if _status_scenarios is not None else state.scenarios,
            state.scenario_verdicts,
            scenario_0=state.scenario_0,
            queued_scenarios=_status_queued,
            verdict_reasons=state.scenario_verdict_reasons,
        )

    # --- Phase 2: poll concretizers in parallel, launch agent as each finishes ---
    def _concretize_and_launch(
            scenario: QAScenario,
            concretize_pane: str,
            win_name: str,
            cname: str,
            transcript: str,
            clone_path: Path,
            instruction_content: str | None = None,
    ) -> None:
        refined_steps, reject_reason = _concretize_scenario(
            scenario, pr_data, data, concretize_pane,
            session_id=scenario.concretize_session_id,
            scenario_cwd=container_workdir,
            instruction_content=instruction_content,
            route_watch=_RouteStallWatch(
                state, _route_checker(pr_data, data, "qa_concretize",
                                      session_tag=state.session_tag,
                                      container_name=cname),
                f"Scenario {scenario.index} refiner"),
        )
        if reject_reason:
            state.scenario_verdicts[scenario.index] = VERDICT_INPUT_REQUIRED
            state.scenario_verdict_reasons[scenario.index] = (
                _concretize_failure_label(reject_reason)
            )
            state.latest_output = (
                f"Scenario {scenario.index} ({scenario.title}): "
                f"{VERDICT_INPUT_REQUIRED} — {_concretize_failure_label(reject_reason)}"
            )
            _log.info("Refiner rejected scenario %d — skipping worker launch: %s",
                      scenario.index, reject_reason)
            return
        if refined_steps:
            scenario.steps = refined_steps

        if not _route_gate(state, pr_data, data, scenario, "qa_scenario",
                           container_name=cname, deferred=_route_deferred):
            _drop_deferred_launch(session, scenario, win_name, _route_deferred,
                                  container_name=cname)
            return
        exec_cmd, pane_cwd = _build_scenario_run_cmd(
            scenario, state, data, transcript, _qa_resolution,
            session=None, workdir_path=workdir_path,
        )
        try:
            scenario_pane = tmux_mod.split_pane_at(
                concretize_pane, "v", exec_cmd, background=True,
                cwd=pane_cwd)
            scenario.window_name = win_name
            scenario.pane_id = scenario_pane
            scenario.transcript_path = transcript
            try:
                from pm_core.claude_launcher import session_id_from_transcript
                scenario.session_id = session_id_from_transcript(transcript)
            except Exception:
                scenario.session_id = None
        except Exception:
            _log.warning("Failed to split scenario pane for scenario %d",
                         scenario.index, exc_info=True)

        if scenario.window_name:
            _log.info("Launched scenario %d (%s) in container %s (window %s)",
                      scenario.index, scenario.title, cname, win_name)
            try:
                from pm_core import pane_layout
                win_id = tmux_mod.pane_window_id(concretize_pane)
                if win_id:
                    pane_layout.register_and_rebalance(session, win_id, [
                        (concretize_pane, f"qa-concretize-s{scenario.index}", "concretize"),
                        (scenario_pane, f"qa-scenario-s{scenario.index}", exec_cmd),
                    ])
            except Exception:
                _log.debug("Registration/rebalance failed for scenario %d",
                           scenario.index, exc_info=True)
        else:
            _log.warning("Scenario %d (%s) container/window creation failed",
                         scenario.index, scenario.title)

    threads = [
        threading.Thread(
            target=_concretize_and_launch,
            args=entry,
            daemon=True,
            name=f"concretize-{entry[0].index}",
        )
        for entry in pending
    ]
    for t in threads:
        t.start()
    for t in threads:
        t.join()


