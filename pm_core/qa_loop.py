"""QA loop: planning + mock generation + parallel execution of QA scenarios.

Three-phase process:
  Phase 1   — Planning: A Claude session analyzes the PR and generates
  a structured test plan.  The plan may request NEW_MOCK blocks for
  external dependencies that need mocking.
  Phase 1.5 — Mock generation: Each requested new mock is generated by
  a separate Claude prompt and saved to pm/qa/mocks/ before scenarios run.
  Phase 2   — Execution: Each scenario from the plan becomes a child
  QA session, running in its own tmux window (qa-{display_id}-s{N}).

Verdicts (shared with review):
  PASS           — Scenario passed, no issues found.
  NEEDS_WORK     — Issues found and fixed (committed and pushed by the scenario).
  INPUT_REQUIRED — Issues found but not fixed, or ambiguity requiring human judgment.
"""

