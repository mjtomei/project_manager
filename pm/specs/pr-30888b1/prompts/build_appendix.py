"""Regenerate impl.md's Appendix A from prompts/after/*.txt (render.py output).

    python build_appendix.py      # run from anywhere

Also writes prompts/diff.txt (unified diff, origin/master render → branch
render) so the inline text and the change summary cannot drift.
"""
import difflib
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = HERE.parent / "impl.md"
AFTER = HERE / "after"
BEFORE = HERE / "before"

SECTIONS = [
    ("A.1 `pm plan add` session prompt (project with existing PRs)", "plan_add"),
    ("A.2 `pm plan add` on a project with no PRs (listing block omitted)", "plan_add_no_existing_prs"),
    ("A.3 Background check `REVIEW_PROMPTS[\"plan-add\"]`", "check_plan-add"),
    ("A.4 `pm plan review`, pre-load variant (no PRs linked to the plan yet)", "plan_review_preload"),
    ("A.5 `pm guide` setup prompt at `has_plan_draft`", "guide_setup_has_plan_draft"),
    ("A.6 `STEP_DESCRIPTIONS[\"has_plan_draft\"]` (TUI log label)", "guide_step_description_has_plan_draft"),
    ("A.7 `prompt_gen.tui_section` (embedded in plan, guide, impl prompts)", "tui_section"),
    ("A.8 Watcher review session prompt (`generate_watcher_review_prompt`)", "watcher_review"),
]

LEGEND = """\
Placeholder legend (all runtime values are written `⟦…⟧`):

- `⟦name⟧`: the NAME argument to `pm plan add` (a title or a file path).
- `⟦plan_id⟧`: the generated plan id (`plan-<sha7>`).
- `⟦pm_root⟧`: the pm state root (the directory that holds `project.yaml`).
- `⟦plan_path⟧`: `⟦pm_root⟧/<plan file>`.
- `⟦session⟧`: the base pm tmux session name.
- `⟦meta_pm_root⟧`: the watcher's meta pm root.
- `⟦project_name⟧` and `⟦repo⟧`: from `project.yaml`.
- `⟦tui_section …⟧`: the block in A.7. It is empty when there is no pm tmux session.
- `⟦notes_block …⟧`: `notes.notes_section(root)`, unchanged by this PR.
- `⟦bounded listing …⟧`: `bounded_join` over the PRs, unchanged in shape from master's `plan breakdown` listing.
- `⟦beginner_mode_section …⟧`: `guide._beginner_mode_guide_section()`, unchanged by this PR.

Removed prompts: `pm plan breakdown` (the whole prompt; its master text is in
`prompts/before/plan_breakdown.txt`) and `REVIEW_PROMPTS["plan-breakdown"]`
(`prompts/before/check_plan-breakdown.txt`). Diff of every prompt, master →
branch: `prompts/diff.txt`.
"""


def main() -> None:
    parts = ["## Appendix A — Full prompt text\n",
             "Generated by `prompts/render.py` + `prompts/build_appendix.py` "
             "from the real builders on this branch; do not hand-edit.\n",
             LEGEND]
    for title, stem in SECTIONS:
        body = (AFTER / f"{stem}.txt").read_text()
        fence = "````" if "```" in body else "```"
        parts.append(f"### {title}\n\n{fence}text\n{body.rstrip()}\n{fence}\n")
    appendix = "\n".join(parts)

    spec = SPEC.read_text()
    head = re.split(r"^## Appendix A — Full prompt text\n", spec, flags=re.M)[0]
    SPEC.write_text(head.rstrip() + "\n\n" + appendix)

    diffs = []
    for p in sorted(set(x.stem for x in BEFORE.iterdir()) | set(x.stem for x in AFTER.iterdir())):
        b = BEFORE / f"{p}.txt"
        a = AFTER / f"{p}.txt"
        bl = b.read_text().splitlines(keepends=True) if b.exists() else []
        al = a.read_text().splitlines(keepends=True) if a.exists() else []
        diffs.extend(difflib.unified_diff(bl, al, f"master/{p}", f"branch/{p}"))
    (HERE / "diff.txt").write_text("".join(diffs))
    print("appendix + diff written")


if __name__ == "__main__":
    main()
