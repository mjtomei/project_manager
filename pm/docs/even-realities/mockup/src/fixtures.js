const SPEC_214_V2 = `# Backoff and jitter for sync retries
Spec impl · pr-214 · generated by the impl session.

## 1. Requirements
- R1. Retry transient GitHub sync failures (HTTP 502/503/504, connection reset) from pm_core/pr_sync.py instead of failing the whole sync. Permanent failures (401, 404) still fail at once.
- R2. Use exponential backoff starting at 2 s, doubling per attempt, at most 6 attempts.
- R3. Record each retry in the PR history journal with attempt number, delay and error, so the TUI and glasses can show what PM is waiting for.
- R4. A sync already waiting on a retry must not be started twice. A second request joins the pending one and reports its remaining delay.

## 2. Implicit requirements
- Respect GitHub's Retry-After header when it is longer than the computed delay.
- Retries must not hold project.yaml's lock while sleeping; take the lock only to write the result.
- Interrupting PM during a wait cancels the retry cleanly and records a cancelled attempt.

## 3. Ambiguities
- A1. Jitter. The description says "with jitter" without a scheme. Proposed: equal jitter (half fixed, half random) so delays never drop below 1 s.
- A2. Cap. No maximum delay is given. Proposed: cap a single delay at 60 s.
- A3. Scope. Should pm pr sync-github use the same policy as the background sync? Proposed: yes, one shared policy.

## 4. Edge cases
- Rate limiting (403 with a zero remaining quota) is not a transient error; wait for the reset time and show it as a hold, not a retry.
- Clock changes during a wait use a monotonic clock.
- A merge started while a sync is retrying waits for the sync result instead of reading stale PR state.
- Offline at startup: one attempt, then report offline without retrying in a tight loop.`;

